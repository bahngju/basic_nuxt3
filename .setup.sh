#!/bin/bash

# ============================================
# Setup Script for Git Hooks
# --------------------------------------------
# 목적:
# 1. 사용자 이름을 입력받아 .author 파일에 저장
# 2. Git이 .githooks 폴더를 hook 경로로 사용하도록 설정
# 3. hook 파일 실행 권한 부여
#
# 사용 방법:
# ./setup.sh
# ============================================

echo "🔧 Git hooks 설정 시작..."

# --------------------------------------------
# 현재 디렉토리가 Git 레포지토리인지 확인
# (.git 폴더가 없으면 종료)
# --------------------------------------------
if [ ! -d ".git" ]; then
  echo "❌ Git 레포지토리가 아닙니다."
  exit 1
fi

# --------------------------------------------
# 사용자 이름 입력 받기
# (커밋 메시지에 표시될 이름)
# --------------------------------------------
read -p "이름을 입력하세요 (커밋에 표시됩니다): " USER_NAME

# --------------------------------------------
# 이름이 비어있는 경우 예외 처리
# --------------------------------------------
if [ -z "$USER_NAME" ]; then
  echo "❌ 이름은 비어 있을 수 없습니다."
  exit 1
fi

# --------------------------------------------
# .githooks 폴더 존재 여부 확인
# --------------------------------------------
if [ ! -d ".githooks" ]; then
  echo "❌ .githooks 폴더가 없습니다."
  exit 1
fi

# --------------------------------------------
# 입력받은 이름을 .author 파일에 저장
# (hook에서 이 값을 읽어서 사용)
# --------------------------------------------
echo "$USER_NAME" > .githooks/.author

# --------------------------------------------
# Git hook 경로 변경
# 기본: .git/hooks
# 변경: .githooks
# --------------------------------------------
git config core.hooksPath .githooks

# --------------------------------------------
# hook 파일 실행 권한 부여
# (권한 없으면 hook 실행 안 됨)
# --------------------------------------------
chmod +x .githooks/*

# --------------------------------------------
# 완료 메시지 출력
# --------------------------------------------
echo "✅ Git hooks 설정 완료!"
echo "👤 설정된 이름: $USER_NAME"
echo "이제 커밋 시 자동으로 hook이 실행됩니다."